from collections.abc import Callable
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol, Self
from uuid import UUID

from app.application.agents.ports import AgentRepository
from app.application.knowledge.ports import KnowledgeRepository
from app.domain.project import Project, ProjectContext
from app.domain.video import Video, VideoSource


class ProjectRepository(Protocol):
    def avatar_assignments(self, owner: UUID) -> dict[UUID, list[UUID]]: ...
    def attach_avatar_voice(self, project: UUID, voice: UUID, owner: UUID) -> UUID: ...
    def avatar_workspace(self, owner: UUID) -> tuple[UUID, bool]: ...
    def list_clients(
        self, query: str, mode: str | None, offset: int, limit: int
    ) -> dict: ...
    def update_client(
        self, project_id: UUID, revision: int, settings: dict
    ) -> bool: ...
    def list_owned(
        self, owner_id: UUID, limit: int, cursor: UUID | None
    ) -> list[Project]: ...
    def create(self, owner_id: UUID, name: str) -> Project: ...
    def get_owned(self, project_id: UUID, owner_id: UUID) -> Project | None: ...
    def rename(self, project_id: UUID, name: str, revision: int) -> Project | None: ...
    def context(self, project_id: UUID) -> ProjectContext: ...
    def save_context(
        self, context: ProjectContext, revision: int
    ) -> ProjectContext | None: ...
    def valid_source_versions(
        self, project_id: UUID, version_ids: list[UUID]
    ) -> bool: ...


class VideoRepository(Protocol):
    def voices(self, project: UUID) -> dict[str, str]: ...
    def avatar_library(self, project: UUID) -> UUID | None: ...
    def next_production(self, now: datetime) -> Video | None: ...
    def finish_due(self, project: UUID) -> None: ...
    def list_videos(self, project: UUID, status: str, query: str) -> list[Video]: ...
    def get(self, project: UUID, video: UUID, lock: bool) -> Video | None: ...
    def save(self, video: Video) -> None: ...
    def delete(self, video: Video) -> None: ...
    def sources(
        self, project: UUID, ids: list[UUID] | None = None
    ) -> list[VideoSource]: ...


class ProjectUnitOfWork(Protocol):
    agent: AgentRepository
    videos: VideoRepository
    knowledge: KnowledgeRepository
    repository: ProjectRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, exc_type: object, exc: object, traceback: object) -> None: ...
    def commit(self) -> None: ...


ProjectUnitOfWorkFactory = Callable[[], AbstractContextManager[ProjectUnitOfWork]]
